#!/usr/bin/env python3
"""Build downstream developer exports from AST-D01-01, AST-D01-02, and AST-D03-01.

Emits a ready-to-consume `@irvantri/design-system` bundle into `dist/`:
  * `tokens.css`           copy of generated `AST-D01-02_Design-Tokens.css`
  * `components.css`       copy of `AST-D03-01_Component-Kit.css`
  * `tokens.ts`            typed TypeScript ESM token & CSS variable maps
  * `tokens.tailwind.css`  Tailwind CSS v4 `@theme` mapping directly to `--is-*`
  * `tailwind.preset.cjs`  Tailwind CSS v3 preset referencing `var(--is-...)`
  * `package.json`         package manifest with `exports` map

Usage (from the repository root):
    python3 tools/build_tokens_exports.py
    python3 tools/build_tokens_exports.py --out-dir dist
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "Standards Design"
DEFAULT_JSON = LIB / "02_Assets/AST-D01-01_Design-Tokens.json"
DEFAULT_CSS = LIB / "02_Assets/AST-D01-02_Design-Tokens.css"
DEFAULT_KIT = LIB / "02_Assets/AST-D03-01_Component-Kit.css"
DEFAULT_OUT = ROOT / "dist"

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_tokens_css as btc  # noqa: E402


def collect_css_tokens(master: dict) -> list[dict]:
    """Return ordered list of emitted semantic/component tokens with resolved values."""
    toks = dict(btc.flatten(master))
    out: list[dict] = []
    for tier in ("semantic", "component"):
        for name, t in toks.items():
            if not name.startswith(tier + "."):
                continue
            css_var = t.get("$extensions", {}).get("cssVar")
            if not css_var:
                continue
            out.append({
                "path": name,
                "tier": tier,
                "type": t.get("$type", ""),
                "cssVar": css_var,
                "value": btc.resolve(toks, t["$value"]),
            })
    return out


def build_typescript(master: dict, items: list[dict]) -> str:
    meta = master.get("meta", {})
    lines = [
        "/*",
        " * Irvantri Standards Design System — Generated TypeScript Tokens",
        f" * Source: {meta.get('file', 'AST-D01-01')} ({meta.get('pinnedVersion', '')})",
        " * Generated by tools/build_tokens_exports.py; do not edit manually.",
        " */",
        "",
        "export const tokens = {",
    ]
    for it in items:
        lines.append(f"  {json.dumps(it['path'])}: {json.dumps(it['value'])},")
    lines += ["} as const;", "", "export const cssVars = {"]
    for it in items:
        var_ref = f"var({it['cssVar']})"
        lines.append(f"  {json.dumps(it['path'])}: {json.dumps(var_ref)},")
    lines += [
        "} as const;",
        "",
        "export type TokenKey = keyof typeof tokens;",
        "export type TokenValue<K extends TokenKey> = (typeof tokens)[K];",
        "export type CssVarRef<K extends TokenKey> = (typeof cssVars)[K];",
        "",
    ]
    return "\n".join(lines)


def _tailwind_key(css_var: str) -> tuple[str, str] | None:
    """Map an --is-* variable name to a Tailwind (category, token) pair."""
    if css_var.startswith("--is-color-"):
        return "color", css_var.removeprefix("--is-color-")
    if css_var.startswith("--is-font-family-"):
        return "font", css_var.removeprefix("--is-font-family-")
    if css_var.startswith("--is-space-"):
        return "spacing", css_var.removeprefix("--is-space-")
    if css_var.startswith("--is-radius-"):
        return "radius", css_var.removeprefix("--is-radius-")
    if css_var.startswith("--is-shadow-"):
        return "shadow", css_var.removeprefix("--is-shadow-")
    return None


def build_tailwind_v4(master: dict, items: list[dict]) -> str:
    meta = master.get("meta", {})
    lines = [
        "/*",
        " * Irvantri Standards Design System — Tailwind CSS v4 @theme bridge",
        f" * Source: {meta.get('file', 'AST-D01-01')} ({meta.get('pinnedVersion', '')})",
        " * Load tokens.css first, then import this file in your main stylesheet.",
        " */",
        "@theme {",
    ]
    for it in items:
        mapped = _tailwind_key(it["cssVar"])
        if not mapped:
            continue
        cat, key = mapped
        lines.append(f"  --{cat}-is-{key}: var({it['cssVar']});")
    lines.append("}")
    return "\n".join(lines) + "\n"


def build_tailwind_v3_preset(master: dict, items: list[dict]) -> str:
    meta = master.get("meta", {})
    theme: dict[str, dict[str, str]] = {
        "colors": {},
        "fontFamily": {},
        "spacing": {},
        "borderRadius": {},
        "boxShadow": {},
    }
    cat_map = {
        "color": "colors",
        "font": "fontFamily",
        "spacing": "spacing",
        "radius": "borderRadius",
        "shadow": "boxShadow",
    }
    for it in items:
        mapped = _tailwind_key(it["cssVar"])
        if not mapped:
            continue
        cat, key = mapped
        theme[cat_map[cat]][f"is-{key}"] = f"var({it['cssVar']})"

    body = json.dumps({"theme": {"extend": theme}}, indent=2)
    return (
        "/*\n"
        " * Irvantri Standards Design System — Tailwind CSS v3 Preset\n"
        f" * Source: {meta.get('file', 'AST-D01-01')} ({meta.get('pinnedVersion', '')})\n"
        " */\n"
        f"module.exports = {body};\n"
    )


def build_package_json(master: dict) -> str:
    meta = master.get("meta", {})
    d01_ver = meta.get("sourceStandards", {}).get("D01", "v1.0.0").lstrip("v")
    pkg = {
        "name": "@irvantri/design-system",
        "version": d01_ver,
        "description": "Irvantri Standards Design System tokens (CSS, TypeScript, Tailwind) and component kit.",
        "license": "UNLICENSED",
        "private": True,
        "exports": {
            "./tokens.css": "./tokens.css",
            "./components.css": "./components.css",
            "./tailwind.css": "./tokens.tailwind.css",
            "./tailwind.preset": "./tailwind.preset.cjs",
            "./tokens": "./tokens.ts",
        },
        "files": [
            "tokens.css",
            "components.css",
            "tokens.ts",
            "tokens.tailwind.css",
            "tailwind.preset.cjs",
        ],
    }
    return json.dumps(pkg, indent=2) + "\n"


def export_bundle(
    out_dir: Path = DEFAULT_OUT,
    tokens_json: Path = DEFAULT_JSON,
    tokens_css: Path = DEFAULT_CSS,
    kit_css: Path = DEFAULT_KIT,
) -> dict[str, Path]:
    master = json.loads(tokens_json.read_text(encoding="utf-8"))
    items = collect_css_tokens(master)
    out_dir.mkdir(parents=True, exist_ok=True)

    files = {
        "tokens.css": tokens_css.read_text(encoding="utf-8"),
        "components.css": kit_css.read_text(encoding="utf-8"),
        "tokens.ts": build_typescript(master, items),
        "tokens.tailwind.css": build_tailwind_v4(master, items),
        "tailwind.preset.cjs": build_tailwind_v3_preset(master, items),
        "package.json": build_package_json(master),
    }
    written: dict[str, Path] = {}
    for name, content in files.items():
        p = out_dir / name
        p.write_text(content, encoding="utf-8")
        written[name] = p
    return written


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--tokens-json", type=Path, default=DEFAULT_JSON)
    ap.add_argument("--tokens-css", type=Path, default=DEFAULT_CSS)
    ap.add_argument("--kit-css", type=Path, default=DEFAULT_KIT)
    args = ap.parse_args(argv)

    written = export_bundle(args.out_dir, args.tokens_json, args.tokens_css, args.kit_css)
    print(f"Built @irvantri/design-system bundle in {args.out_dir} ({len(written)} files):")
    for name, p in written.items():
        print(f"  {name} ({p.stat().st_size} B)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
